import * as fs from "node:fs";
import * as path from "node:path";
import { type Agent, type AgentId, findAgent, sharedSkillsDir } from "./agents.ts";
import {
  canonicalPath,
  children,
  exists,
  type Files,
  linkTarget,
  walk,
  writeAtomic,
} from "./files.ts";
import { syncodeDir } from "./paths.ts";

interface Link {
  source: string;
  destination: string;
}

export interface Plan {
  generated?: { file: string; content: string; detail: string };
  links: Link[];
}

export const GITIGNORE_LINES = [".generated/", "instructions/local.md", ".DS_Store"];

export const repoPaths = (repo: string) => ({
  instructions: path.join(repo, "instructions"),
  skills: path.join(repo, "skills"),
  agents: path.join(repo, "agents"),
  generated: path.join(repo, ".generated", "AGENTS.md"),
});

function osName(): "macos" | "linux" {
  return process.platform === "darwin" ? "macos" : "linux";
}

export function enabledAgents(ids: readonly AgentId[]): Agent[] {
  return ids.flatMap((id) => findAgent(id) ?? []);
}

function listSkills(repo: string): string[] {
  return children(repoPaths(repo).skills).filter((dir) =>
    fs.existsSync(path.join(dir, "SKILL.md")),
  );
}

/**
 * Instructions are `AGENTS.md` plus optional `<os>.md` and untracked
 * `local.md`. A lone `AGENTS.md` is linked directly so agent edits land in
 * the repo; otherwise the parts are composed into one generated file.
 */
function instructionsSource(repo: string): Pick<Plan, "generated"> & { source?: string } {
  const dir = repoPaths(repo).instructions;
  const main = path.join(dir, "AGENTS.md");
  if (!fs.existsSync(main)) return {};
  const parts = [main, path.join(dir, `${osName()}.md`), path.join(dir, "local.md")].filter(
    (file) => fs.existsSync(file),
  );
  if (parts.length === 1) return { source: main };

  const file = repoPaths(repo).generated;
  const sections = parts.map((part) => fs.readFileSync(part, "utf8").trim()).filter(Boolean);
  const content = `${[
    "<!-- Generated by syncode. Edit the files in instructions/, then run `syncode apply`. -->",
    ...sections,
  ].join("\n\n")}\n`;
  const detail = `from ${parts.map((part) => path.relative(repo, part)).join(" + ")}`;
  return { source: file, generated: { file, content, detail } };
}

function plan(repo: string, agents: readonly Agent[]): Plan {
  const links: Link[] = [];
  const { source: instructions, generated } = instructionsSource(repo);

  if (instructions) {
    for (const agent of agents) {
      if (agent.instructions) {
        links.push({
          source: instructions,
          destination: path.join(agent.home(), agent.instructions),
        });
      }
    }
  }

  const skillRoots = [
    ...(agents.some((agent) => !agent.ownSkills) ? [sharedSkillsDir()] : []),
    ...agents.filter((agent) => agent.ownSkills).map((agent) => path.join(agent.home(), "skills")),
  ];
  // Whole skill directories are linked: Codex ignores a symlinked SKILL.md.
  for (const skill of listSkills(repo)) {
    for (const root of skillRoots) {
      links.push({ source: skill, destination: path.join(root, path.basename(skill)) });
    }
  }

  for (const agent of agents) {
    const dir = path.join(repoPaths(repo).agents, agent.id);
    for (const file of walk(dir)) {
      links.push({ source: file, destination: path.join(agent.home(), path.relative(dir, file)) });
    }
  }

  // Drop destinations that are the same entry as an earlier one.
  const seen = new Set<string>();
  const unique = links.filter((link) => {
    const key = canonicalPath(link.destination);
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
  return generated ? { generated, links: unique } : { links: unique };
}

// Links made by the last apply, so links dropped from the plan get pruned.
function stateFile(): string {
  return path.join(syncodeDir(), "state.json");
}

function readState(): string[] {
  try {
    const value: unknown = JSON.parse(fs.readFileSync(stateFile(), "utf8"));
    if (
      typeof value === "object" &&
      value !== null &&
      "links" in value &&
      Array.isArray(value.links)
    ) {
      return value.links.filter((item): item is string => typeof item === "string");
    }
  } catch {
    // Missing or unreadable state only means nothing gets pruned.
  }
  return [];
}

export async function apply(files: Files, agents: readonly Agent[]) {
  const { generated, links } = plan(files.repo, agents);
  if (generated) files.compose(generated.file, generated.content, generated.detail);

  for (const link of links) {
    // In a dry run the generated file may not exist yet, so compare content.
    const preview = link.source === generated?.file && files.dryRun ? generated.content : undefined;
    await files.link(link.source, link.destination, preview);
  }

  const wanted = new Set(links.map((link) => canonicalPath(link.destination)));
  for (const destination of readState()) {
    if (!wanted.has(canonicalPath(destination))) files.prune(destination);
  }

  if (!files.dryRun) {
    const linked = links
      .filter((link) => linkTarget(link.destination) !== undefined)
      .map((link) => link.destination);
    writeAtomic(stateFile(), `${JSON.stringify({ links: linked }, null, 2)}\n`);
  }
}

/** Replaces every managed link with a copy of its target. */
export function unlinkAll(files: Files, agents: readonly Agent[]) {
  const { links } = plan(files.repo, agents);
  for (const link of links) files.copyBack(link.source, link.destination);
  if (!files.dryRun && exists(stateFile())) fs.rmSync(stateFile());
}
